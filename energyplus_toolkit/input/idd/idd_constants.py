# Column where the "\" of IDD field and tag lines starts: "  A1 , \field", "       \note"
IDD_TAG_COLUMN = 7
BLOCK_INDENT = " " * IDD_TAG_COLUMN

COMMENT_ONLY_OBJECT_NAME = "CommentOnly"
COMMENT_ONLY_OBJECT_TEXT = "CommentOnly; ! Autogenerated comment only object."

# Magic numeric value used in the IDD to signal autosize / autocalculate defaults.
AUTOSIZE_VALUE = -99999.0


def format_leading(field_id: str | None = None, is_last_field: bool = False) -> str:
    """Formats the leading part of an IDD field line with proper indentation.

    Args:
        field_id: The field identifier (e.g. ``A1``, ``N3``).
        is_last_field: When True, the separator is ``;`` instead of ``,``.

    Returns:
        The formatted leading string for the IDD field line.
    """
    if field_id:
        separator = ";" if is_last_field else ","
        return f"  {field_id.ljust(IDD_TAG_COLUMN - 4)}{separator:1s} "
    else:
        return BLOCK_INDENT
