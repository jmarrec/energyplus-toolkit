NUMBER_OF_SPACES = 7
BLOCK_INDENT = " " * NUMBER_OF_SPACES

COMMENT_ONLY_OBJECT_NAME = "CommentOnly"
COMMENT_ONLY_OBJECT_TEXT = "CommentOnly; ! Autogenerated comment only object."

AUTOSIZE_VALUE = -99999.0


def format_leading(field_id: str | None = None, is_last_field: bool = False) -> str:
    """Formats the leading part of an IDD line with proper indentation.

    Args:
        field_id (str | None): The field identifier to format.
        separator (str | None): The separator character to use after the field ID.

    Returns:
        str: The formatted leading string for the IDD line.

    Raises:
        ValueError: If field_id is provided but separator is None.
    """
    if field_id:
        separator = ";" if is_last_field else ","
        return f"  {field_id.ljust(NUMBER_OF_SPACES - 4)}{separator:1s} "
    else:
        return BLOCK_INDENT
